for job in "${top_level_jobs[@]}"; do
    run_test "$job"
done

# Print results
echo
num_jobs=${#ci_jobs[@]}
line=$(printf '=%.0s' $(seq 1 $((13 + $(get_max_job_name_length) + 2*${#num_jobs}))))
echo -e "${bold}${line}\nResults\n${line}${normal}"
