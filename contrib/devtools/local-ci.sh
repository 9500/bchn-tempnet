    ./src/bench/bench_bitcoin -evals=1
}
host_arm64_binfmt_support_required() {
    export QEMU_LD_PREFIX="/usr/aarch64-linux-gnu"
    local error=0

    if [ ! -d /proc/sys/fs/binfmt_misc ]; then
        # Missing binfmt_misc definitely indicates lack of support
        error=1
    elif [ -f /bchn/build/src/bitcoin-wallet ]; then
        # Try simply running bitcoin-wallet to confirm the environment is sound
        if ! /bchn/build/src/bitcoin-wallet info >/dev/null 2>&1; then
            error=1
        fi
    else
        error=2
    fi

    if [ "$error" -gt 0 ]; then
        if [ "$error" -eq 1 ]; then
            echo -e "${red}ERROR: ARM64 binfmt/QEMU support does not appear to be available${normal}"
            echo "These tests execute ARM64 Linux binaries transparently, which requires"
            echo "binfmt_misc support with a qemu-aarch64 handler in the Linux environment"
            echo "running Docker."
        else
            echo -e "${red}WARNING${normal}: build/src/bitcoin-wallet not found. Skipping ARM64 support test."
            echo "ARM64 binfmt/QEMU support might not be available, meaning the ARM functional tests might not run."
        fi
        echo
        echo "If need be, try installing the required packages, e.g. on Debian/Ubuntu:"
        echo "  sudo apt install qemu-user-static binfmt-support"
        echo
        echo "or via Docker:"
        echo "  docker run --privileged --rm tonistiigi/binfmt --install arm64"
    fi

    if [ "$error" -eq 1 ]; then
        return 1
    fi
    return 0
}
get_max_job_name_length() {
    max_length=0;
    for j in "${ci_jobs[@]}"; do
        l=${#j};
        if ((l>max_length)); then
            max_length=$l
        fi
    done
    echo "$max_length"
}

