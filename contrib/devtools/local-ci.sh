    build-debian-debug-tests
    test-debian-debug-unittests
    sanitizer-undefined
    build-debian-debug-clang
    build-debian-debug-clang-tests
    test-debian-debug-clang-unittests
    build-win-64-depends
    build-win-64
    build-aarch64-depends
    build-aarch64
    build-aarch64-tests
