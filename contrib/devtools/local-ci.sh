test-aarch64-functional() {
    needs build-aarch64 || return
    ninja -t restat &&
    host_arm64_binfmt_support_required &&
    non_tests="example_test|test_runner|combine_logs|create_cache" &&
    long_tests="abc-p2p-compactblocks|abc-p2p-fullblocktest|feature_block|feature_dbcrash|feature_pruning|mining_getblocktemplate_longpoll|p2p_timeouts|wallet_backup" &&
    excluded_tests="getblocktemplate_errors|getblocktemplate-timing" &&
    ui_tests="$(find ../test/functional/*.py -exec basename {} \; | grep ^ui | tr '\n' '|' | sed 's/|$//')" &&
    mapfile -t tests < <(find ../test/functional/*.py -exec basename {} \; | grep -Ev "($non_tests|$long_tests|$excluded_tests|$ui_tests)") &&
    ./test/functional/test_runner.py "${tests[@]}"
}
fuzz-libfuzzer() {
    needs nothing || return
    cd /bchn/buildFuzzer &&
    debian-clang-env &&
    [ -d "qa-assets" ] || git clone --branch master --single-branch --depth=1 https://gitlab.com/bitcoin-cash-node/bchn-sw/qa-assets.git &&
    clear_cmake &&
    cmake -GNinja .. -DENABLE_MAN=OFF -DCCACHE=OFF -DENABLE_SANITIZERS="fuzzer;address" &&
    ninja bitcoin-fuzzers link-fuzz-test_runner.py &&
    ./test/fuzz/test_runner.py -l DEBUG ./qa-assets/fuzz_seed_corpus/
}
