# A simple script to run all .gitlab-ci.yml jobs locally. It is manually curated,
# so any changes to .gitlab-ci.yml may need corresponding adustments here.
#
# You can watch a summary of the pipeline progress in a second terminal with:
#
#   docker exec $(docker ps -ql) bash -c 'tail -n +1 -f $(ls /tmp/ci-results*)'

export LC_ALL=C
export TRAVIS=1
export CCACHE_BASEDIR=/bchn/
export CCACHE_DIR=/bchn/ccache
export CCACHE_COMPILERCHECK=content

docker_image=docker.io/bitcoincashnode/buildenv@sha256:f4ebe3d250eebbff0a78d078199ef58f161da3a1a2c5d0d2d0609898242ab9ce # debian-v7

PROJECT_ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)/../..
DOCKER=${DOCKER:-docker}

# Build a command line argument for docker, enabling interactive mode if stdin
# is a tty and enabling tty in docker if stdout is a tty.
export DOCKER_RUN_TTY=""
if [ -t 0 ] ; then export DOCKER_RUN_TTY="${DOCKER_RUN_TTY}i" ; fi
if [ -t 1 ] ; then export DOCKER_RUN_TTY="${DOCKER_RUN_TTY}t" ; fi
if [ -n "$DOCKER_RUN_TTY" ] ; then export DOCKER_RUN_TTY="-${DOCKER_RUN_TTY}" ; fi

# Only set color variables if stdout is a tty
if [ -t 1 ]; then
    red="\e[1;31m" green="\e[1;32m" yellow="\e[1;33m" bold="\e[1m" normal="\e[0m"
else
    red="" green="" yellow="" bold="" normal=""
fi

# Pass "--clean" to clear remnants generated by the script
clean_arg=""
confirm_clean() {
    # Just proceed if stdin is not a tty
    [ -t 0 ] || { clean_arg="--clean"; return; }

    echo "This will delete:"
    rm_dirs=(build buildFuzzer ccache depends/work depends/aarch64-linux-gnu depends/x86_64-w64-mingw32 depends/sources depends/built)
    for dir in "${rm_dirs[@]}"; do
        echo "  $(realpath "$PROJECT_ROOT")/$dir"
    done
    read -erp "Ok to proceed? (y/N): " answer
    if [[ $answer == "y" || $answer == "Y" ]]; then
        clean_arg="--clean"
    else
        echo "Not deleting"
        exit
    fi
}

if [ "${INSIDE_DOCKER:-}" != "1" ]; then
    if [[ "$1" == "--clean" ]]; then
        confirm_clean
    fi
    mounts=(-v "$PROJECT_ROOT:/bchn:ro")
    if [ -f "$PROJECT_ROOT/.git" ]; then
        repo=$(git -C "$PROJECT_ROOT" rev-parse --path-format=absolute --git-common-dir) || exit
        mounts+=(-v "$repo:$repo:ro")
    fi
    rw_dirs=("build" "buildFuzzer" "ccache" "depends" "src/bench")
    mkdir -p "${rw_dirs[@]/#/$PROJECT_ROOT/}"
    for rw_dir in "${rw_dirs[@]}"; do
        mounts+=(-v "$PROJECT_ROOT/$rw_dir:/bchn/$rw_dir")
    done
    cmd=("$DOCKER" run --rm "$DOCKER_RUN_TTY" \
        "${mounts[@]}" \
        -w /bchn \
        -e "INSIDE_DOCKER=1" \
        "$docker_image" \
        bash -c "/bchn/contrib/devtools/local-ci.sh $clean_arg")
    echo -e "Running: ${bold}${cmd[*]}${normal}"
    echo
    "${cmd[@]}"
    exit_code=$?
    if [[ $clean_arg == "--clean" ]]; then
        cd "$PROJECT_ROOT" || exit 1
        rm -rvf build buildFuzzer ccache
    fi
    exit $exit_code
fi

if [[ $1 == "--clean" ]]; then
    cd /bchn || exit 1
    rm -rvf build/* buildFuzzer/* ccache/* depends/work depends/aarch64-linux-gnu depends/x86_64-w64-mingw32 depends/sources depends/built
    exit
fi

if [ -f /sys/fs/cgroup/pids.max ] && [ "$(cat /sys/fs/cgroup/pids.max)" -le 2048 ]; then
    echo -e "${red}WARNING: The container is running with a pids limit of $(cat /sys/fs/cgroup/pids.max), which may cause some tests to fail. Consider increasing the limit.${normal}"
fi

sed -i 's/include-system-site-packages = false/include-system-site-packages = true/' /opt/venv/pyvenv.cfg
# shellcheck disable=SC1091
. /opt/venv/bin/activate
git config --global --add safe.directory /bchn
logdir=/bchn/build/ci-logs
mkdir -p "$logdir"
cd /bchn/build || exit 1

# Limit ccache to 3 GB (from default 5 GB).
# 'ninja all check bench_bitcoin' produces ~2.1GB cache (Jan 2021)
ccache -M 3G

jobs_run=()
run_test() {
    job=$1
    job_num=$((${#jobs_run[@]}+1))
    num_jobs=${#ci_jobs[@]}

    # Do not rerun jobs
    for j in "${jobs_run[@]}"; do
        [[ "$j" == "$job" ]] && return
    done

    # Print job header
    charlen=$((${#job}+${#job_num}+${#num_jobs}+7))
    line="$(printf '=%.0s' $(seq 1 $charlen))"
    echo
    echo -e "${yellow}$line"
    echo -e "${yellow}Job ${job_num}/${num_jobs}:${normal} ${bold}$1${normal}"
    echo -e "${yellow}$line${normal}"

    # Run job and record result
    column_width=$(($(get_max_job_name_length) + 2))
    fmt="${yellow}Job %*s/${num_jobs}:${normal} ${bold}%-${column_width}s${normal}"
    printf "$fmt" "${#num_jobs}" "$job_num" "$job:" >> "$results"
    $job |& tee "$logdir/$job.log"
    exit_code=${PIPESTATUS[0]}
    if [ "$exit_code" -eq 0 ]; then
        echo -e "${green}pass${normal}" | tee -a "$results"
    else
        echo -e "${red}FAIL${normal}" | tee -a "$results"
    fi
    jobs_run+=("$job")

    # Recursively run dependents
    IFS=' ' read -r -a deps <<< "${dependents["$job"]}"
    for dep in "${deps[@]}"; do
        if [[ "$dep" != "nothing" ]]; then
            run_test "$dep"
        fi
    done
}
gather_dependencies() {
    gathering_dependencies=true
    prev_num_jobs=${#ci_jobs[@]}
    while true; do
        for job in "${ci_jobs[@]}"; do
            $job
        done
        new_num_jobs=${#ci_jobs[@]}
        [ "$new_num_jobs" -gt "$prev_num_jobs" ] || break
        prev_num_jobs=$new_num_jobs
    done
    gathering_dependencies=false
}
needs() {
    if ! $gathering_dependencies; then return; fi
    requirement="$1"
    dependent="${FUNCNAME[1]}"
    if [ -n "${dependents["$requirement"]}" ]; then
       dependents["$requirement"]+=" "
    fi
    dependents["$requirement"]+="$dependent"
    if [[ "$requirement" != "nothing" ]]; then
        found_requirement=false
        for job in "${ci_jobs[@]}"; do
            if [[ "$job" == "$requirement" ]];  then
                found_requirement=true
            fi
        done
        if ! $found_requirement; then
            ci_jobs+=("$requirement")
            echo -e "Added an extra required job: ${yellow}$dependent${normal} needs ${yellow}$requirement${normal}"
        fi
    fi
    return 1
}

# Some helpers
clear_cmake() {
    rm -rf CMakeCache.txt CMakeFiles native/CMakeCache.txt native/CMakeFiles
}
